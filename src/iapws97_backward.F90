    pure elemental function backward_temperature(p, input, region, entropy) result(T)
        implicit none
        real(real64) :: T
        real(real64), intent(in) :: p, input
        integer, intent(in) :: region
        logical, intent(in) :: entropy
        real(real64) :: q, z, boundary

        T = ieee_value(0d0, ieee_quiet_nan)
        if (.not. ieee_is_finite(p) .or. .not. ieee_is_finite(input)) return
        if (p <= 0d0 .or. p > 100d6 .or. abs(input) > 1d7) return
        q = p * 1d-6
        z = input * 1d-3
        if (entropy) then
            if (abs(z) > 100d0) return
            select case (region)
            case (1)
                T = polynomial(q, z + 2d0, s1_Li, s1_Lj, s1_n)
            case (2)
                if (q <= 4d0) then
                    T = polynomial(sqrt(sqrt(q)), z / 2d0 - 2d0, s2a_Li, s2a_Lj, s2a_n)
                else if (z >= 5.85d0) then
                    T = polynomial(q, 10d0 - z / 0.7853d0, s2b_Li, s2b_Lj, s2b_n)
                else
                    T = polynomial(q, 2d0 - z / 2.9251d0, s2c_Li, s2c_Lj, s2c_n)
                end if
            case (3)
                if (z <= 4.41202148223476d0) then
                    T = 760d0 * polynomial(q / 100d0 + 0.24d0, z / 4.4d0 - 0.703d0, s3a_Li, s3a_Lj, s3a_n)
                else
                    T = 860d0 * polynomial(q / 100d0 + 0.76d0, z / 5.3d0 - 0.818d0, s3b_Li, s3b_Lj, s3b_n)
                end if
            end select
        else
            select case (region)
            case (1)
                T = polynomial(q, z / 2500d0 + 1d0, h1_Li, h1_Lj, h1_n)
            case (2)
                if (q <= 4d0) then
                    T = polynomial(q, z / 2000d0 - 2.1d0, h2a_Li, h2a_Lj, h2a_n)
                else if (q <= 6.546699678d0) then
                    T = polynomial(q - 2d0, z / 2000d0 - 2.6d0, h2b_Li, h2b_Lj, h2b_n)
                else
                    boundary = 2652.6571908428d0 + sqrt((q - 4.5257578905948d0) / 1.2809002730136d-4)
                    if (z >= boundary) then
                        T = polynomial(q - 2d0, z / 2000d0 - 2.6d0, h2b_Li, h2b_Lj, h2b_n)
                    else
                        T = polynomial(q + 25d0, z / 2000d0 - 1.8d0, h2c_Li, h2c_Lj, h2c_n)
                    end if
                end if
            case (3)
                boundary = 2014.64004206875d0 + q * (3.74696550136983d0 + &
                    q * (-0.0219921901054187d0 + 8.75131686009950d-5 * q))
                if (z <= boundary) then
                    T = 760d0 * polynomial(q / 100d0 + 0.24d0, z / 2300d0 - 0.615d0, h3a_Li, h3a_Lj, h3a_n)
                else
                    T = 860d0 * polynomial(q / 100d0 + 0.298d0, z / 2800d0 - 0.72d0, h3b_Li, h3b_Lj, h3b_n)
                end if
            end select
        end if
    end function backward_temperature

    pure function polynomial(x, y, ix, iy, n) result(polynomial_sum)
        implicit none
        real(real64) :: polynomial_sum
        real(real64), intent(in) :: x, y, n(:)
        integer, intent(in) :: ix(:), iy(:)
        real(real64) :: xp(-32:50), yp(-32:50), inv
        integer :: k

        polynomial_sum = ieee_value(0d0, ieee_quiet_nan)
        if (minval(ix) < 0 .and. abs(x) < 1d-10) return
        if (minval(iy) < 0 .and. abs(y) < 1d-10) return
        xp(0) = 1d0
        yp(0) = 1d0
        do k = 1, maxval(ix)
            xp(k) = xp(k-1) * x
        end do
        do k = 1, maxval(iy)
            yp(k) = yp(k-1) * y
        end do
        if (minval(ix) < 0) then
            inv = 1d0 / x
            do k = -1, minval(ix), -1
                xp(k) = xp(k+1) * inv
            end do
        end if
        if (minval(iy) < 0) then
            inv = 1d0 / y
            do k = -1, minval(iy), -1
                yp(k) = yp(k+1) * inv
            end do
        end if
        polynomial_sum = 0d0
        do k = 1, size(n)
            polynomial_sum = polynomial_sum + n(k) * xp(ix(k)) * yp(iy(k))
        end do
    end function polynomial
