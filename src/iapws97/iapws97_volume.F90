    pure character function subregion(T, P, Ts) result(region)
        real(real64), intent(in) :: T, P, Ts
        real(real64), parameter :: ef_slope = 3.727888004d0
        real(real64), parameter :: p643 = 21.04336731897525d0
        real(real64) :: ef

        ef = 647.096d0 + ef_slope * (P - 22.064d0)
        if (P > 40d0) then
            region = merge('a', 'b', T <= log_boundary(P, tab))
        else if (T <= boundary(P, cd) .and. P > 19.00881189173929d0) then
            region = 'c'
        else if (P > 25d0) then
            if (T > ef) then
                region = 'f'
            else
                region = merge('d', 'e', T <= log_boundary(P, tab))
            end if
        else if (P > 23d0) then
            if (T <= boundary(P, gh)) then
                region = merge('g', 'l', P > 23.5d0)
            else if (T <= ef) then
                region = 'h'
            else if (T <= boundary(P, ij)) then
                region = 'i'
            else
                region = merge('j', 'k', T <= boundary(P, jk))
            end if
        else if (P > 22.5d0) then
            if (T <= boundary(P, gh)) then
                region = 'l'
            else if (T <= boundary(P, mn)) then
                region = 'm'
            else if (T <= ef) then
                region = 'n'
            else if (T <= log_boundary(P, top)) then
                region = 'o'
            else if (T <= boundary(P, ij)) then
                region = 'p'
            else
                region = merge('j', 'k', T <= boundary(P, jk))
            end if
        else if (P > p643) then
            if (T <= boundary(P, qu)) then
                region = 'q'
            else if (T > boundary(P, rx)) then
                region = merge('r', 'k', T <= boundary(P, jk))
            else if (P > 22.064d0) then
                if (P > 22.11d0) then
                    region = interval(T, [boundary(P, uv), ef, log_boundary(P, twx)], 'uvwx')
                else
                    region = interval(T, [boundary(P, uv), ef, log_boundary(P, twx)], 'uyzx')
                end if
            else if (T > Ts) then
                region = 'x'
                if (P > 21.90096265d0 .and. T <= log_boundary(P, twx)) region = 'z'
            else
                region = 'u'
                if (P > 21.93161551d0 .and. T > boundary(P, uv)) region = 'y'
            end if
        else if (P > 20.5d0) then
            if (T <= Ts) then
                region = 's'
            else
                region = merge('r', 'k', T <= boundary(P, jk))
            end if
        else if (P > 19.00881189173929d0) then
            region = merge('s', 't', T <= Ts)
        else
            region = merge('c', 't', T <= Ts)
        end if
    end function subregion

    pure character function interval(T, limits, regions) result(region)
        real(real64), intent(in) :: T, limits(:)
        character(*), intent(in) :: regions
        integer :: i
        i = 1 + count(T > limits)
        region = regions(i:i)
    end function interval

    pure function boundary(P, a) result(T)
        implicit none
        real(real64) :: T
        real(real64), intent(in) :: P, a(:)
        integer :: i
        T = a(size(a))
        do i = size(a)-1, 1, -1
            T = a(i) + P * T
        end do
    end function boundary

    pure function log_boundary(P, a) result(T)
        implicit none
        real(real64) :: T
        real(real64), intent(in) :: P, a(5)
        real(real64) :: x
        x = log(P)
        T = a(1) + x * (a(2) + x * a(3)) + (a(4) + a(5) / x) / x
    end function log_boundary

