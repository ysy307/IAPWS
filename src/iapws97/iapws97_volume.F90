        if (abs(x) < 1d-10) then
            v = ieee_value(0d0, ieee_quiet_nan)
            return
        end if
        x1 = x
        xm1 = 1d0 / x1
        x2 = x1 * x1
        xm2 = xm1 * xm1
        xm3 = xm1 * xm2
        xm4 = xm2 * xm2
