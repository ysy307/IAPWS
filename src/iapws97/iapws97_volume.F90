        y6 = y3 * y3
        y4 = y2 * y2
        y8 = y4 * y4
        y10 = y5 * y5
        y12 = y6 * y6
        v = &
            a_n(1) * xm12 * y5 + a_n(2) * xm12 * y10 + a_n(3) * xm12 * y12 + &
            a_n(4) * xm10 * y5 + a_n(5) * xm10 * y10 + a_n(6) * xm10 * y12 + &
            a_n(7) * xm8 * y5 + a_n(8) * xm8 * y8 + a_n(9) * xm8 * y10 + &
            a_n(10) * xm6 * y1 + a_n(11) * xm5 * y1 + a_n(12) * xm5 * y5 + &
            a_n(13) * xm5 * y10 + a_n(14) * xm4 * y8 + a_n(15) * xm3 + &
